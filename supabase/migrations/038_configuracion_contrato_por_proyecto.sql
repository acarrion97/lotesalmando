-- ============================================================
-- 038: CONFIGURACION DEL CONTRATO POR PROYECTO
-- ============================================================
-- La configuracion legal del contrato (representante, ciudad,
-- cuentas, direccion de canje y RUC) hasta ahora era UNA por empresa
-- (tabla `configuracion`). Cada proyecto puede ser una razon social
-- distinta, asi que ahora se guarda por proyecto:
--
--   * una fila por (empresa, proyecto), con UNIQUE;
--   * un campo vacio se toma de `configuracion` (empresa);
--   * el RUC vacio se toma de `empresa.ruc`.
--
-- Se edita desde Contratos -> boton "Configuracion" (selector de
-- proyecto).
--
-- Ejecutar en el SQL Editor de Supabase. Idempotente.
-- ============================================================

CREATE TABLE IF NOT EXISTS configuracion_contrato (
    id_configuracion_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER NOT NULL,
    id_proyecto INTEGER NOT NULL,

    -- Razon social / RUC que firma este proyecto (vacio = empresa.ruc).
    ruc TEXT,
    -- Quien firma como propietario (gerente / apoderado).
    representante TEXT,
    representante_cedula TEXT,
    representante_email TEXT,
    -- Ciudad donde se firma el contrato.
    ciudad TEXT,
    -- Cuentas donde se reciben los pagos (texto libre, una por linea).
    cuentas_bancarias TEXT,
    -- Direccion donde se canjean las papeletas de deposito.
    direccion_canje TEXT,

    CONSTRAINT fk_configuracion_contrato_empresa
        FOREIGN KEY (id_empresa)
        REFERENCES empresa(id_empresa)
        ON DELETE CASCADE,

    CONSTRAINT fk_configuracion_contrato_proyecto
        FOREIGN KEY (id_proyecto)
        REFERENCES proyectos(id_proyecto)
        ON DELETE CASCADE,

    CONSTRAINT uq_configuracion_contrato_proyecto
        UNIQUE (id_empresa, id_proyecto)
);

COMMENT ON TABLE configuracion_contrato IS 'Datos legales del contrato por proyecto (los vacios se toman de configuracion/empresa)';
COMMENT ON COLUMN configuracion_contrato.ruc IS 'Razon social / RUC de este proyecto (vacio = empresa.ruc)';
COMMENT ON COLUMN configuracion_contrato.representante IS 'Quien firma como propietario en el contrato de este proyecto';
COMMENT ON COLUMN configuracion_contrato.representante_cedula IS 'Cedula del representante';
COMMENT ON COLUMN configuracion_contrato.representante_email IS 'Correo electronico del representante';
COMMENT ON COLUMN configuracion_contrato.ciudad IS 'Ciudad donde se firma el contrato';
COMMENT ON COLUMN configuracion_contrato.cuentas_bancarias IS 'Cuentas bancarias para el pago del contrato (texto libre)';
COMMENT ON COLUMN configuracion_contrato.direccion_canje IS 'Direccion para canjear papeletas de deposito por recibos';

-- RLS: se define la politica igual que en 006_row_level_security.sql,
-- pero NO se activa: 008_disable_rls_emergency_rollback.sql dejo RLS
-- apagado en todo el esquema porque con el rol `authenticated` no
-- permitia ni leer ni escribir. Para reactivarla en el futuro alcanza
-- con el ALTER TABLE que queda al final.
DROP POLICY IF EXISTS configuracion_contrato_all ON configuracion_contrato;
CREATE POLICY configuracion_contrato_all ON configuracion_contrato FOR ALL TO authenticated
  USING (id_empresa = current_empresa_id())
  WITH CHECK (id_empresa = current_empresa_id());

