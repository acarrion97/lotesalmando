CREATE OR REPLACE FUNCTION public.crear_recibo_para_pago(
  p_id_pago INTEGER,
  p_id_cobranza INTEGER
)
RETURNS public.recibos
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_empresa_id INTEGER;
  v_proyecto_id INTEGER;
  v_codigo_establecimiento CHAR(3);
  v_punto_emision CHAR(3);
  v_secuencia BIGINT;
  v_numero_recibo VARCHAR(17);
  v_pago public.pagos%ROWTYPE;
  v_recibo public.recibos%ROWTYPE;
  v_cedula TEXT;
  v_tipo_identificacion CHAR(2);
  v_identificacion VARCHAR(20);
  v_subtotal NUMERIC(15, 2);
  v_iva NUMERIC(15, 2);
  v_razon_social TEXT;
  v_ruc TEXT;
  v_direccion_matriz TEXT;
  v_direccion_establecimiento TEXT;
  v_detalle TEXT;
  v_receptor_nombre TEXT;
BEGIN
  IF public.current_empresa_id() IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;

  SELECT p.*
    INTO v_pago
    FROM public.pagos p
   WHERE p.id_pago = p_id_pago
     AND p.id_cobranza = p_id_cobranza;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe el pago asociado a la cuota';
  END IF;

  SELECT pr.id_empresa,
         pr.id_proyecto,
         COALESCE(NULLIF(btrim(cc.codigo_establecimiento), ''), '001'),
         COALESCE(NULLIF(btrim(cc.punto_emision), ''), '001'),
         COALESCE(NULLIF(btrim(cc.razon_social), ''), em.razon_social),
         COALESCE(NULLIF(btrim(cc.ruc), ''), em.ruc),
         NULLIF(btrim(cc.direccion_matriz), ''),
         NULLIF(btrim(cc.direccion_establecimiento), ''),
         cl.nombres,
         cl.cedula_ruc,
         format(
           'Pago de cuota %s del contrato %s - Lote %s, proyecto %s',
           c.numero_cuota,
           ct.numero_contrato,
           l.numero_lote,
           pr.nombre
         )
    INTO v_empresa_id,
         v_proyecto_id,
         v_codigo_establecimiento,
         v_punto_emision,
         v_razon_social,
         v_ruc,
         v_direccion_matriz,
         v_direccion_establecimiento,
         v_receptor_nombre,
         v_cedula,
         v_detalle
    FROM public.cobranzas c
    JOIN public.contratos ct ON ct.id_contrato = c.id_contrato
    JOIN public.ventas v ON v.id_venta = ct.id_venta
    JOIN public.cliente cl ON cl.id_cliente = v.id_cliente
    JOIN public.lotes l ON l.id_lote = v.id_lote
    JOIN public.manzana_bloque mb ON mb.id_manzana = l.id_manzana
    JOIN public.etapas e ON e.id_etapa = mb.id_etapa
    JOIN public.proyectos pr ON pr.id_proyecto = e.id_proyecto
    JOIN public.empresa em ON em.id_empresa = pr.id_empresa
    LEFT JOIN public.configuracion_contrato cc
      ON cc.id_empresa = pr.id_empresa AND cc.id_proyecto = pr.id_proyecto
   WHERE c.id_cobranza = p_id_cobranza;

  IF v_empresa_id IS DISTINCT FROM public.current_empresa_id() THEN
    RAISE EXCEPTION 'No tiene permiso para emitir recibos de esta empresa';
  END IF;
  IF v_razon_social IS NULL OR btrim(v_razon_social) = ''
     OR v_ruc IS NULL OR btrim(v_ruc) = ''
     OR v_direccion_matriz IS NULL
     OR v_direccion_establecimiento IS NULL THEN
    RAISE EXCEPTION 'Complete razón social, RUC y direcciones fiscales del proyecto antes de confirmar el pago';
  END IF;
  IF v_codigo_establecimiento !~ '^[0-9]{3}$'
     OR v_punto_emision !~ '^[0-9]{3}$' THEN
    RAISE EXCEPTION 'Los códigos de establecimiento y punto de emisión deben contener tres dígitos';
  END IF;

  v_cedula := regexp_replace(COALESCE(v_cedula, ''), '[^0-9]', '', 'g');
  IF v_cedula = '' THEN
    v_tipo_identificacion := '07';
    v_identificacion := '9999999999999';
    v_receptor_nombre := 'CONSUMIDOR FINAL';
  ELSIF length(v_cedula) = 10 THEN
    v_tipo_identificacion := '05';
    v_identificacion := v_cedula;
  ELSIF length(v_cedula) = 13 THEN
    v_tipo_identificacion := '04';
    v_identificacion := v_cedula;
  ELSE
    RAISE EXCEPTION 'La identificación del cliente debe tener 10 dígitos, 13 dígitos o estar vacía';
  END IF;

  v_subtotal := round(v_pago.monto_pagado / 1.15, 2);
  v_iva := v_pago.monto_pagado - v_subtotal;

  INSERT INTO public.recibo_secuencias (
    id_empresa,
    codigo_establecimiento,
    punto_emision,
    secuencia
  )
  VALUES (
    v_empresa_id,
    v_codigo_establecimiento,
    v_punto_emision,
    1
  )
  ON CONFLICT (id_empresa, codigo_establecimiento, punto_emision)
  DO UPDATE SET secuencia = public.recibo_secuencias.secuencia + 1
  RETURNING secuencia INTO v_secuencia;

  v_numero_recibo := format(
    '%s-%s-%s',
    v_codigo_establecimiento,
    v_punto_emision,
    lpad(v_secuencia::TEXT, 9, '0')
  );

  INSERT INTO public.recibos (
    id_empresa,
    id_proyecto,
    id_pago,
    id_cobranza,
    numero_recibo,
    secuencia,
    fecha_emision,
    emisor_razon_social,
    emisor_ruc,
    emisor_direccion_matriz,
    emisor_direccion_establecimiento,
    codigo_establecimiento,
    punto_emision,
    receptor_nombre,
    receptor_tipo_identificacion,
    receptor_identificacion,
    detalle,
    subtotal,
    porcentaje_iva,
    iva,
    total,
    forma_pago
  )
  VALUES (
    v_empresa_id,
    v_proyecto_id,
    v_pago.id_pago,
    p_id_cobranza,
    v_numero_recibo,
    v_secuencia,
    v_pago.fecha_pago,
    v_razon_social,
    v_ruc,
    v_direccion_matriz,
    v_direccion_establecimiento,
    v_codigo_establecimiento,
    v_punto_emision,
    v_receptor_nombre,
    v_tipo_identificacion,
    v_identificacion,
    v_detalle,
    v_subtotal,
    15,
    v_iva,
    v_pago.monto_pagado,
    v_pago.forma_pago
  )
  RETURNING * INTO v_recibo;

  RETURN v_recibo;
END;
$$;

CREATE OR REPLACE FUNCTION public.confirmar_pago_con_recibo(
  p_id_cobranza INTEGER,
  p_id_usuario INTEGER,
  p_monto_pagado NUMERIC,
  p_fecha_pago DATE,
  p_forma_pago TEXT,
  p_id_comprobante BIGINT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_empresa_id INTEGER;
  v_estado TEXT;
  v_comprobante public.comprobantes%ROWTYPE;
  v_pago public.pagos%ROWTYPE;
  v_recibo public.recibos%ROWTYPE;
BEGIN
  IF public.current_empresa_id() IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;
  IF public.usuario_empresa_id(p_id_usuario) IS DISTINCT FROM public.current_empresa_id() THEN
    RAISE EXCEPTION 'El usuario no pertenece a la empresa activa';
  END IF;
  IF p_forma_pago NOT IN ('efectivo', 'transferencia', 'deposito', 'tarjeta', 'cheque', 'otro') THEN
    RAISE EXCEPTION 'Seleccione una forma de pago válida';
  END IF;

  SELECT c.estado, pr.id_empresa
    INTO v_estado, v_empresa_id
    FROM public.cobranzas c
    JOIN public.contratos ct ON ct.id_contrato = c.id_contrato
    JOIN public.ventas v ON v.id_venta = ct.id_venta
    JOIN public.lotes l ON l.id_lote = v.id_lote
    JOIN public.manzana_bloque mb ON mb.id_manzana = l.id_manzana
    JOIN public.etapas e ON e.id_etapa = mb.id_etapa
    JOIN public.proyectos pr ON pr.id_proyecto = e.id_proyecto
   WHERE c.id_cobranza = p_id_cobranza
   FOR UPDATE OF c;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No encontramos la cuota a pagar';
  END IF;
  IF v_empresa_id IS DISTINCT FROM public.current_empresa_id() THEN
    RAISE EXCEPTION 'No tiene permiso para registrar pagos de esta empresa';
  END IF;
  IF v_estado = 'pagada' OR EXISTS (
    SELECT 1 FROM public.pagos WHERE id_cobranza = p_id_cobranza
  ) THEN
    RAISE EXCEPTION 'La cuota ya tiene un pago registrado';
  END IF;

  IF p_id_comprobante IS NOT NULL THEN
    SELECT * INTO v_comprobante
      FROM public.comprobantes
     WHERE id_comprobante = p_id_comprobante
       AND id_cobranza = p_id_cobranza
     FOR UPDATE;
    IF NOT FOUND OR v_comprobante.estado <> 'pendiente' THEN
      RAISE EXCEPTION 'El comprobante no existe o ya fue revisado';
    END IF;
    p_monto_pagado := v_comprobante.monto_pagado;
  END IF;

  IF p_monto_pagado IS NULL OR p_monto_pagado <= 0 THEN
    RAISE EXCEPTION 'El monto pagado debe ser mayor a cero';
  END IF;

  INSERT INTO public.pagos (id_cobranza, id_usuario, monto_pagado, fecha_pago, forma_pago)
  VALUES (
    p_id_cobranza,
    p_id_usuario,
    p_monto_pagado,
    COALESCE(p_fecha_pago, CURRENT_DATE),
    p_forma_pago
  )
  RETURNING * INTO v_pago;

  UPDATE public.cobranzas
     SET estado = 'pagada'
   WHERE id_cobranza = p_id_cobranza;

  IF p_id_comprobante IS NOT NULL THEN
    UPDATE public.comprobantes
       SET estado = 'aprobado',
           revisado_en = now(),
           id_revisado_por = p_id_usuario,
           nota_rechazo = NULL
     WHERE id_comprobante = p_id_comprobante
     RETURNING * INTO v_comprobante;
  END IF;

  v_recibo := public.crear_recibo_para_pago(v_pago.id_pago, p_id_cobranza);

  RETURN jsonb_build_object(
    'pago', to_jsonb(v_pago),
    'recibo', to_jsonb(v_recibo),
    'comprobante', CASE
      WHEN p_id_comprobante IS NULL THEN NULL
      ELSE to_jsonb(v_comprobante)
    END
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.get_recibos_por_pagos(p_ids_pago INTEGER[])
RETURNS SETOF public.recibos
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path = public, pg_temp
AS $$
BEGIN
  IF public.current_empresa_id() IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;

  RETURN QUERY
  SELECT r.*
    FROM public.recibos r
   WHERE r.id_empresa = public.current_empresa_id()
     AND r.id_pago = ANY(COALESCE(p_ids_pago, ARRAY[]::INTEGER[]))
   ORDER BY r.fecha_emision DESC, r.id_recibo DESC;
END;
$$;

