CREATE TABLE IF NOT EXISTS public.recibo_secuencias (
  id_empresa INTEGER NOT NULL REFERENCES public.empresa(id_empresa) ON DELETE CASCADE,
  codigo_establecimiento CHAR(3) NOT NULL,
  punto_emision CHAR(3) NOT NULL,
  secuencia BIGINT NOT NULL DEFAULT 0 CHECK (secuencia >= 0),
  PRIMARY KEY (id_empresa, codigo_establecimiento, punto_emision)
);

CREATE TABLE IF NOT EXISTS public.recibos (
  id_recibo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa INTEGER NOT NULL REFERENCES public.empresa(id_empresa) ON DELETE RESTRICT,
  id_proyecto INTEGER NOT NULL REFERENCES public.proyectos(id_proyecto) ON DELETE RESTRICT,
  id_pago INTEGER NOT NULL REFERENCES public.pagos(id_pago) ON DELETE RESTRICT,
  id_cobranza INTEGER NOT NULL REFERENCES public.cobranzas(id_cobranza) ON DELETE RESTRICT,
  numero_recibo VARCHAR(17) NOT NULL,
  secuencia BIGINT NOT NULL CHECK (secuencia > 0),
  fecha_emision DATE NOT NULL,
  emisor_razon_social TEXT NOT NULL,
  emisor_ruc VARCHAR(20) NOT NULL,
  emisor_direccion_matriz TEXT NOT NULL,
  emisor_direccion_establecimiento TEXT NOT NULL,
  codigo_establecimiento CHAR(3) NOT NULL,
  punto_emision CHAR(3) NOT NULL,
  receptor_nombre TEXT NOT NULL,
  receptor_tipo_identificacion CHAR(2) NOT NULL,
  receptor_identificacion VARCHAR(20) NOT NULL,
  detalle TEXT NOT NULL,
  subtotal NUMERIC(15, 2) NOT NULL CHECK (subtotal >= 0),
  porcentaje_iva NUMERIC(5, 2) NOT NULL DEFAULT 15 CHECK (porcentaje_iva = 15),
  iva NUMERIC(15, 2) NOT NULL CHECK (iva >= 0),
  total NUMERIC(15, 2) NOT NULL CHECK (total > 0),
  forma_pago TEXT NOT NULL CHECK (forma_pago IN (
    'efectivo',
    'transferencia',
    'deposito',
    'tarjeta',
    'cheque',
    'otro',
    'no_especificada'
  )),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT recibos_uno_por_pago UNIQUE (id_pago),
  CONSTRAINT recibos_numero_empresa_unico UNIQUE (id_empresa, numero_recibo),
  CONSTRAINT recibos_secuencia_unica UNIQUE (
    id_empresa,
    codigo_establecimiento,
    punto_emision,
    secuencia
  ),
  CONSTRAINT recibos_total_cuadra CHECK (subtotal + iva = total),
  CONSTRAINT recibos_numero_formato CHECK (numero_recibo ~ '^[0-9]{3}-[0-9]{3}-[0-9]{9}$')
);

CREATE INDEX IF NOT EXISTS idx_recibos_empresa_fecha
  ON public.recibos (id_empresa, fecha_emision DESC);

ALTER TABLE public.recibo_secuencias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.recibos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS recibo_secuencias_empresa ON public.recibo_secuencias;
CREATE POLICY recibo_secuencias_empresa ON public.recibo_secuencias
  FOR ALL TO authenticated
  USING (id_empresa = public.current_empresa_id())
  WITH CHECK (id_empresa = public.current_empresa_id());

DROP POLICY IF EXISTS recibos_empresa ON public.recibos;
CREATE POLICY recibos_empresa ON public.recibos
  FOR ALL TO authenticated
  USING (id_empresa = public.current_empresa_id())
  WITH CHECK (id_empresa = public.current_empresa_id());

