GRANT EXECUTE ON FUNCTION public.confirmar_pago_con_recibo(INTEGER, INTEGER, NUMERIC, DATE, TEXT, BIGINT) TO authenticated;
REVOKE ALL ON FUNCTION public.get_recibos_por_pagos(INTEGER[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_recibos_por_pagos(INTEGER[]) TO authenticated;
