-- =============================================
-- Lotes al Mando - Editar y eliminar pagos
-- =============================================
-- Corrige equivocaciones de carga y limpia pagos repetidos:
--   * permisos `editar_pagos` / `eliminar_pagos` (el frontend los pide con
--     usePuede; hasta ahora solo existian ver_pagos y confirmar_pagos),
--   * tabla `pagos_eliminaciones`: auditoria con el motivo obligatorio que
--     el usuario escribe al borrar,
--   * RPC `editar_pago` y `eliminar_pago` (SECURITY DEFINER, igual que
--     confirmar_pago_con_recibo): hacen todo en una transaccion y en la BD,
--     donde viven las FK y los disparadores.
--
-- Reglas que imponen las funciones:
--   * eliminar SOLO un pago de una cuota que tenga mas de uno (pagos
--     repetidos); un pago unico de su cuota no se puede borrar,
--   * el motivo es obligatorio (minimo 5 caracteres),
--   * al borrar se borra tambien el recibo del pago (FK RESTRICT) y la cuota
--     vuelve a pendiente/vencida/pagada segun lo que queda cubierto,
--   * el trigger trg_ventas_estado_por_cuotas recalcula el estado de la
--     venta cuando cambia la cuota.
--
-- Idempotente: se puede re-ejecutar sin efecto secundario.

-- ------------------------------------------------------------
-- 1) Permisos
-- ------------------------------------------------------------
INSERT INTO permiso (nombre_permiso, modulo) VALUES
  ('editar_pagos',   'pagos'),
  ('eliminar_pagos', 'pagos')
ON CONFLICT DO NOTHING;

-- Mismo criterio que 024 para las acciones sensibles del area financiera:
-- Administrador y Gerente (Vendedor no toca el dinero ya cobrado).
INSERT INTO rol_permiso (id_rol, id_permiso)
SELECT r.id_rol, p.id_permiso
FROM roles r
CROSS JOIN permiso p
WHERE p.nombre_permiso IN ('editar_pagos', 'eliminar_pagos')
  AND r.nombre_rol IN ('Administrador', 'Gerente')
ON CONFLICT (id_rol, id_permiso) DO NOTHING;

SELECT setval(
  pg_get_serial_sequence('permiso', 'id_permiso'),
  COALESCE((SELECT MAX(id_permiso) FROM permiso), 1),
  true
);

-- ------------------------------------------------------------
-- 2) Auditoria de pagos eliminados
-- ------------------------------------------------------------
-- Sin FK a `pagos`: la fila ya no existe. `id_cobranza` tampoco tiene FK
-- para que la auditoria sobreviva a un borrado posterior de la cuota.
CREATE TABLE IF NOT EXISTS pagos_eliminaciones (
  id_pago_eliminacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pago INTEGER NOT NULL,
  id_cobranza INTEGER NOT NULL,
  monto_pagado NUMERIC(15, 2) NOT NULL,
  fecha_pago DATE NOT NULL,
  forma_pago TEXT,
  motivo TEXT NOT NULL CHECK (length(btrim(motivo)) > 0),
  id_usuario INTEGER REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  eliminado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE pagos_eliminaciones IS
  'Auditoria de pagos eliminados: guarda el motivo que exige la UI al borrar.';

CREATE INDEX IF NOT EXISTS idx_pagos_eliminaciones_cobranza
  ON pagos_eliminaciones (id_cobranza);

-- ------------------------------------------------------------
-- 3) Recalculo del estado de una cuota
-- ------------------------------------------------------------
-- Criterio: cubre el monto -> 'pagada'; si no, con la fecha ya pasada ->
-- 'vencida'; si no -> 'pendiente'. Al escribir en `cobranzas` el trigger
-- trg_ventas_estado_por_cuotas (migracion 040/041) recalcula la venta.
CREATE OR REPLACE FUNCTION public.recalcular_estado_cuota(p_id_cobranza INTEGER)
RETURNS VARCHAR(50)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_monto NUMERIC(15, 2);
  v_vencimiento DATE;
  v_pagado NUMERIC(15, 2) := 0;
  v_estado VARCHAR(50);
BEGIN
  SELECT c.monto_cuota, c.fecha_vencimiento
    INTO v_monto, v_vencimiento
    FROM public.cobranzas c
   WHERE c.id_cobranza = p_id_cobranza
   FOR UPDATE;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  SELECT COALESCE(SUM(p.monto_pagado), 0)
    INTO v_pagado
    FROM public.pagos p
   WHERE p.id_cobranza = p_id_cobranza;

  IF v_pagado >= v_monto THEN
    v_estado := 'pagada';
  ELSIF v_vencimiento IS NOT NULL AND v_vencimiento < CURRENT_DATE THEN
    v_estado := 'vencida';
  ELSE
    v_estado := 'pendiente';
  END IF;

  UPDATE public.cobranzas
     SET estado = v_estado
   WHERE id_cobranza = p_id_cobranza
     AND estado IS DISTINCT FROM v_estado;

  RETURN v_estado;
END;
$$;

-- ------------------------------------------------------------
-- 4) Eliminar un pago (solo repetidos) con su motivo
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.eliminar_pago(
  p_id_pago INTEGER,
  p_motivo TEXT,
  p_id_usuario INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_pago public.pagos%ROWTYPE;
  v_totales INTEGER;
  v_recibo BOOLEAN := FALSE;
  v_estado VARCHAR(50);
BEGIN
  IF public.current_empresa_id() IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;
  IF p_id_usuario IS NULL
     OR public.usuario_empresa_id(p_id_usuario) IS DISTINCT FROM public.current_empresa_id() THEN
    RAISE EXCEPTION 'El usuario no pertenece a la empresa activa';
  END IF;
  IF p_motivo IS NULL OR length(btrim(p_motivo)) < 5 THEN
    RAISE EXCEPTION 'Indique el motivo de la eliminacion (minimo 5 caracteres)';
  END IF;

  SELECT * INTO v_pago
    FROM public.pagos
   WHERE id_pago = p_id_pago
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pago no existe o ya fue eliminado';
  END IF;

  -- Regla del modulo: solo pagos repetidos. Un pago unico de su cuota no se
  -- toca, aunque el usuario tenga el permiso.
  SELECT count(*) INTO v_totales
    FROM public.pagos
   WHERE id_cobranza = v_pago.id_cobranza;

  IF v_totales < 2 THEN
    RAISE EXCEPTION 'Solo se pueden eliminar pagos repetidos: esta cuota tiene un unico pago';
  END IF;

  -- El recibo apunta al pago con FK RESTRICT: se borra primero. Aviso: si el
  -- recibo ya se valido ante el SRI hay que anularlo alla; aca solo se
  -- retira de la lista.
  DELETE FROM public.recibos WHERE id_pago = p_id_pago;
  v_recibo := FOUND;

  INSERT INTO public.pagos_eliminaciones
    (id_pago, id_cobranza, monto_pagado, fecha_pago, forma_pago, motivo, id_usuario)
  VALUES
    (v_pago.id_pago, v_pago.id_cobranza, v_pago.monto_pagado,
     v_pago.fecha_pago, v_pago.forma_pago, btrim(p_motivo), p_id_usuario);

  DELETE FROM public.pagos WHERE id_pago = p_id_pago;

  v_estado := public.recalcular_estado_cuota(v_pago.id_cobranza);

  RETURN jsonb_build_object(
    'id_pago', v_pago.id_pago,
    'id_cobranza', v_pago.id_cobranza,
    'recibo_eliminado', v_recibo,
    'estado_cuota', v_estado
  );
END;
$$;

-- ------------------------------------------------------------
-- 5) Editar un pago (monto, fecha y forma de pago)
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.editar_pago(
  p_id_pago INTEGER,
  p_monto_pagado NUMERIC,
  p_fecha_pago DATE,
  p_forma_pago TEXT,
  p_id_usuario INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_pago public.pagos%ROWTYPE;
  v_estado VARCHAR(50);
  v_recibo BOOLEAN;
BEGIN
  IF public.current_empresa_id() IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;
  IF p_id_usuario IS NULL
     OR public.usuario_empresa_id(p_id_usuario) IS DISTINCT FROM public.current_empresa_id() THEN
    RAISE EXCEPTION 'El usuario no pertenece a la empresa activa';
  END IF;
  IF p_monto_pagado IS NULL OR p_monto_pagado <= 0 THEN
    RAISE EXCEPTION 'El monto pagado debe ser mayor a cero';
  END IF;
  IF p_forma_pago IS NULL
     OR p_forma_pago NOT IN ('efectivo', 'transferencia', 'deposito', 'tarjeta', 'cheque', 'otro') THEN
    RAISE EXCEPTION 'Seleccione una forma de pago valida';
  END IF;

  SELECT * INTO v_pago
    FROM public.pagos
   WHERE id_pago = p_id_pago
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pago no existe';
  END IF;

  UPDATE public.pagos
     SET monto_pagado = p_monto_pagado,
         fecha_pago = COALESCE(p_fecha_pago, v_pago.fecha_pago),
         forma_pago = p_forma_pago
   WHERE id_pago = p_id_pago
  RETURNING * INTO v_pago;

  -- Si el monto baja y ya no cubre la cuota, la cuota deja de estar pagada.
  v_estado := public.recalcular_estado_cuota(v_pago.id_cobranza);

  -- El recibo emitido conserva el monto con el que salio: se avisa en la UI
  -- para que decidan si reemitirlo por el sistema tributario.
  SELECT EXISTS (SELECT 1 FROM public.recibos WHERE id_pago = p_id_pago)
    INTO v_recibo;

  RETURN jsonb_build_object(
    'pago', to_jsonb(v_pago),
    'estado_cuota', v_estado,
    'tiene_recibo', v_recibo
  );
END;
$$;
