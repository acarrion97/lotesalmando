-- Eliminación auditada en cascada y cédula/RUC único por empresa.

-- Una cédula/RUC repetida por espacios, puntos, guiones o mayúsculas cuenta
-- como el mismo identificador. No se corrigen ni fusionan duplicados previos:
-- la migración se detiene y enumera los registros para su revisión manual.
DO $$
DECLARE
  v_duplicados TEXT;
BEGIN
  SELECT string_agg(
    format('empresa %s, identificacion %s, clientes %s', id_empresa, identificacion, ids),
    E'\n'
  )
    INTO v_duplicados
    FROM (
      SELECT
        id_empresa,
        upper(regexp_replace(btrim(cedula_ruc), '[[:space:].-]+', '', 'g')) AS identificacion,
        array_agg(id_cliente ORDER BY id_cliente) AS ids
      FROM cliente
      WHERE id_empresa IS NOT NULL
        AND cedula_ruc IS NOT NULL
        AND btrim(cedula_ruc) <> ''
      GROUP BY id_empresa, upper(regexp_replace(btrim(cedula_ruc), '[[:space:].-]+', '', 'g'))
      HAVING count(*) > 1
    ) duplicados;

  IF v_duplicados IS NOT NULL THEN
    RAISE EXCEPTION 'No se pudo crear la unicidad de cédula/RUC: hay duplicados que requieren revisión manual.'
      USING DETAIL = v_duplicados;
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_cliente_empresa_identificacion
  ON cliente (
    id_empresa,
    upper(regexp_replace(btrim(cedula_ruc), '[[:space:].-]+', '', 'g'))
  )
  WHERE id_empresa IS NOT NULL
    AND cedula_ruc IS NOT NULL
    AND btrim(cedula_ruc) <> '';

COMMENT ON INDEX uq_cliente_empresa_identificacion IS
  'Una cédula/RUC por empresa; normaliza espacios, puntos, guiones y mayúsculas.';

-- Sin FK al cliente eliminado para que la auditoría sobreviva. El snapshot
-- conserva sus datos; detalle y paths permiten saber qué se eliminó.
CREATE TABLE IF NOT EXISTS clientes_eliminaciones (
  id_eliminacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INTEGER NOT NULL,
  id_empresa INTEGER NOT NULL,
  id_usuario INTEGER REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  cliente_datos JSONB NOT NULL,
  motivo TEXT NOT NULL CHECK (length(btrim(motivo)) BETWEEN 5 AND 1000),
  detalle JSONB NOT NULL DEFAULT '{}'::jsonb,
  archivos_storage JSONB NOT NULL DEFAULT '{}'::jsonb,
  eliminado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE clientes_eliminaciones IS
  'Auditoría de clientes eliminados en cascada; conserva snapshot, motivo y archivos relacionados.';

CREATE INDEX IF NOT EXISTS idx_clientes_eliminaciones_empresa_fecha
  ON clientes_eliminaciones (id_empresa, eliminado_en DESC);

ALTER TABLE clientes_eliminaciones ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS clientes_eliminaciones_select ON clientes_eliminaciones;
CREATE POLICY clientes_eliminaciones_select ON clientes_eliminaciones
  FOR SELECT TO authenticated
  USING (
    id_empresa = current_empresa_id()
    AND usuario_tiene_permiso('ver_clientes')
  );

CREATE OR REPLACE FUNCTION public.eliminar_cliente_en_cascada(
  p_id_cliente INTEGER,
  p_motivo TEXT,
  p_id_usuario INTEGER
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_empresa INTEGER;
  v_usuario_sesion INTEGER;
  v_cliente public.cliente%ROWTYPE;
  v_documentos TEXT[] := ARRAY[]::TEXT[];
  v_comprobantes TEXT[] := ARRAY[]::TEXT[];
  v_detalle JSONB;
  v_id_eliminacion BIGINT;
BEGIN
  v_empresa := public.current_empresa_id();
  IF auth.uid() IS NULL OR v_empresa IS NULL THEN
    RAISE EXCEPTION 'No se pudo identificar la empresa del usuario';
  END IF;
  IF NOT public.usuario_tiene_permiso('eliminar_clientes') THEN
    RAISE EXCEPTION 'No tiene permiso para eliminar clientes';
  END IF;
  IF p_motivo IS NULL OR length(btrim(p_motivo)) < 5 OR length(btrim(p_motivo)) > 1000 THEN
    RAISE EXCEPTION 'Indique el motivo de la eliminacion (entre 5 y 1000 caracteres)';
  END IF;

  SELECT u.id_usuario
    INTO v_usuario_sesion
    FROM public.usuario u
   WHERE lower(u.email) = lower(auth.email())
     AND u.id_empresa = v_empresa
   LIMIT 1;

  IF p_id_usuario IS NULL OR p_id_usuario IS DISTINCT FROM v_usuario_sesion THEN
    RAISE EXCEPTION 'El usuario que realiza la eliminacion no coincide con la sesion';
  END IF;

  SELECT c.*
    INTO v_cliente
    FROM public.cliente c
   WHERE c.id_cliente = p_id_cliente
     AND c.id_empresa = v_empresa
   FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El cliente no existe en la empresa activa o ya fue eliminado';
  END IF;

  SELECT coalesce(array_agg(DISTINCT ct.documento_url) FILTER (WHERE ct.documento_url IS NOT NULL), ARRAY[]::TEXT[])
    INTO v_documentos
    FROM public.contratos ct
    JOIN public.ventas ve ON ve.id_venta = ct.id_venta
   WHERE ve.id_cliente = v_cliente.id_cliente;

  SELECT coalesce(array_agg(DISTINCT cp.archivo_url), ARRAY[]::TEXT[])
    INTO v_comprobantes
    FROM public.comprobantes cp
   WHERE cp.id_cliente = v_cliente.id_cliente;

  SELECT jsonb_build_object(
    'cotizaciones', (SELECT count(*) FROM public.cotizador WHERE id_cliente = v_cliente.id_cliente),
    'ventas', (SELECT count(*) FROM public.ventas WHERE id_cliente = v_cliente.id_cliente),
    'contratos', (
      SELECT count(*)
        FROM public.contratos ct
        JOIN public.ventas ve ON ve.id_venta = ct.id_venta
       WHERE ve.id_cliente = v_cliente.id_cliente
    ),
    'cuotas', (
      SELECT count(*)
        FROM public.cobranzas co
        JOIN public.contratos ct ON ct.id_contrato = co.id_contrato
        JOIN public.ventas ve ON ve.id_venta = ct.id_venta
       WHERE ve.id_cliente = v_cliente.id_cliente
    ),
    'pagos', (
      SELECT count(*)
        FROM public.pagos pa
        JOIN public.cobranzas co ON co.id_cobranza = pa.id_cobranza
        JOIN public.contratos ct ON ct.id_contrato = co.id_contrato
        JOIN public.ventas ve ON ve.id_venta = ct.id_venta
       WHERE ve.id_cliente = v_cliente.id_cliente
    ),
    'recibos', (
      SELECT count(*)
        FROM public.recibos re
        JOIN public.cobranzas co ON co.id_cobranza = re.id_cobranza
        JOIN public.contratos ct ON ct.id_contrato = co.id_contrato
        JOIN public.ventas ve ON ve.id_venta = ct.id_venta
       WHERE ve.id_cliente = v_cliente.id_cliente
    ),
    'comprobantes', (SELECT count(*) FROM public.comprobantes WHERE id_cliente = v_cliente.id_cliente)
  )
    INTO v_detalle;

  INSERT INTO public.clientes_eliminaciones
    (id_cliente, id_empresa, id_usuario, cliente_datos, motivo, detalle, archivos_storage)
  VALUES
    (v_cliente.id_cliente, v_empresa, v_usuario_sesion, to_jsonb(v_cliente), btrim(p_motivo),
     v_detalle, jsonb_build_object('contratos', to_jsonb(v_documentos), 'comprobantes', to_jsonb(v_comprobantes)))
  RETURNING id_eliminacion INTO v_id_eliminacion;

  -- Primero se quitan las FK restrictivas. Después contratos eliminan en
  -- cascada sus cuotas y avisos; ventas y cotizaciones se borran al final.
  DELETE FROM public.comprobantes WHERE id_cliente = v_cliente.id_cliente;

  DELETE FROM public.recibos re
   USING public.pagos pa, public.cobranzas co, public.contratos ct, public.ventas ve
   WHERE re.id_pago = pa.id_pago
     AND re.id_cobranza = co.id_cobranza
     AND co.id_contrato = ct.id_contrato
     AND ct.id_venta = ve.id_venta
     AND ve.id_cliente = v_cliente.id_cliente;

  INSERT INTO public.pagos_eliminaciones
    (id_pago, id_cobranza, monto_pagado, fecha_pago, forma_pago, motivo, id_usuario)
  SELECT pa.id_pago, pa.id_cobranza, pa.monto_pagado, pa.fecha_pago, pa.forma_pago,
         btrim(p_motivo), v_usuario_sesion
    FROM public.pagos pa
    JOIN public.cobranzas co ON co.id_cobranza = pa.id_cobranza
    JOIN public.contratos ct ON ct.id_contrato = co.id_contrato
    JOIN public.ventas ve ON ve.id_venta = ct.id_venta
   WHERE ve.id_cliente = v_cliente.id_cliente;

  DELETE FROM public.pagos pa
   USING public.cobranzas co, public.contratos ct, public.ventas ve
   WHERE pa.id_cobranza = co.id_cobranza
     AND co.id_contrato = ct.id_contrato
     AND ct.id_venta = ve.id_venta
     AND ve.id_cliente = v_cliente.id_cliente;

  DELETE FROM public.contratos ct
   USING public.ventas ve
   WHERE ct.id_venta = ve.id_venta
     AND ve.id_cliente = v_cliente.id_cliente;

  DELETE FROM public.ventas WHERE id_cliente = v_cliente.id_cliente;
  DELETE FROM public.cotizador WHERE id_cliente = v_cliente.id_cliente;
  DELETE FROM public.cliente WHERE id_cliente = v_cliente.id_cliente;

  RETURN jsonb_build_object(
    'id_eliminacion', v_id_eliminacion,
    'documentos_contrato', to_jsonb(v_documentos),
    'comprobantes', to_jsonb(v_comprobantes)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.eliminar_cliente_en_cascada(INTEGER, TEXT, INTEGER) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.eliminar_cliente_en_cascada(INTEGER, TEXT, INTEGER) TO authenticated;
