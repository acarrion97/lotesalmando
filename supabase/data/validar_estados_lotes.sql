-- 1) Resumen: estado actual vs esperado (cuantos lotes en cada combinacion)
SELECT e.estado_esperado,
       COALESCE(l.estado, 'NO EXISTE EN BD') AS estado_actual,
       COUNT(*) AS lotes
FROM esperado_lotes e
JOIN public.manzana_bloque m ON m.nombre_codigo = e.manzana
LEFT JOIN public.lotes l ON l.id_manzana = m.id_manzana
     AND substring(l.numero_lote from '(\d+)$') = e.nro::text
GROUP BY 1, 2
ORDER BY 1, 2;

-- 2) Detalle de lotes que NO cuadran (estado actual distinto del esperado, o inexistentes en BD)
SELECT e.manzana, e.nro, l.id_lote, l.numero_lote,
       l.estado AS estado_actual, e.estado_esperado, e.fuente
FROM esperado_lotes e
JOIN public.manzana_bloque m ON m.nombre_codigo = e.manzana
LEFT JOIN public.lotes l ON l.id_manzana = m.id_manzana
     AND substring(l.numero_lote from '(\d+)$') = e.nro::text
WHERE l.id_lote IS NULL
   OR (e.estado_esperado <> 'revisar' AND l.estado IS DISTINCT FROM e.estado_esperado)
ORDER BY e.manzana, e.nro;

-- 3) Lotes en BD (LADRILLERA H en adelante) que no aparecen en ningun Excel ("en el aire")
SELECT m.nombre_codigo AS manzana, l.id_lote, l.numero_lote, l.estado
FROM public.lotes l
JOIN public.manzana_bloque m ON m.id_manzana = l.id_manzana
LEFT JOIN esperado_lotes e ON e.manzana = m.nombre_codigo
     AND e.nro::text = substring(l.numero_lote from '(\d+)$')
WHERE m.id_manzana >= 4 AND e.manzana IS NULL
ORDER BY m.id_manzana, l.id_lote;

-- 4) Estado de TODOS los lotes con 'reservado' actualmente en BD
SELECT m.nombre_codigo AS manzana, l.id_lote, l.numero_lote, l.estado
FROM public.lotes l
JOIN public.manzana_bloque m ON m.id_manzana = l.id_manzana
WHERE l.estado = 'reservado'
ORDER BY m.id_manzana, l.id_lote;
